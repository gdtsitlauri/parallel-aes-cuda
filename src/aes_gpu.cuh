// equivalent inverse cipher); the host expands them once and copies them with
// cudaMemcpyToSymbol. Every thread block builds the T-table and S-box it needs
// in shared memory from the constant S-boxes, then each thread processes
// blocks in a grid-stride loop. Blocks are 16 bytes in the byte order of
// FIPS-197; they are loaded as uint4 and byte-swapped to big-endian words.
