__device__ __forceinline__ uint32_t rotr8(uint32_t x) { return (x >> 8) | (x << 24); }
__device__ __forceinline__ uint32_t rotr16(uint32_t x) { return (x >> 16) | (x << 16); }
__device__ __forceinline__ uint32_t rotr24(uint32_t x) { return (x >> 24) | (x << 8); }
__device__ __forceinline__ uint32_t bswap(uint32_t x) { return __byte_perm(x, 0, 0x0123); }

__device__ __forceinline__ uint8_t gf_xtime(uint8_t a) { return (uint8_t)((a << 1) ^ ((a & 0x80) ? 0x1b : 0)); }
__device__ __forceinline__ uint8_t gf_mul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        a = gf_xtime(a);
        b >>= 1;
    }
    return p;
}

// Te0[x] = (2s, s, s, 3s) with s = S[x];  Td0[x] = (14t, 9t, 13t, 11t) with t = S^-1[x]
__device__ void build_enc_tables(uint32_t *te0, uint8_t *sb) {
    for (int i = threadIdx.x; i < 256; i += blockDim.x) {
        uint8_t s = c_sbox[i];
        sb[i] = s;
        te0[i] = ((uint32_t)gf_xtime(s) << 24) | ((uint32_t)s << 16) | ((uint32_t)s << 8) |
                 (uint32_t)(gf_xtime(s) ^ s);
    }
    __syncthreads();
}

__device__ void build_dec_tables(uint32_t *td0, uint8_t *isb) {
    for (int i = threadIdx.x; i < 256; i += blockDim.x) {
        uint8_t t = c_inv_sbox[i];
        isb[i] = t;
        td0[i] = ((uint32_t)gf_mul(t, 14) << 24) | ((uint32_t)gf_mul(t, 9) << 16) |
                 ((uint32_t)gf_mul(t, 13) << 8) | (uint32_t)gf_mul(t, 11);
    }
    __syncthreads();
}

__device__ __forceinline__ void encrypt_block(const uint32_t *te0, const uint8_t *sb, uint32_t s[4]) {
    uint32_t s0 = s[0] ^ c_rk[0], s1 = s[1] ^ c_rk[1], s2 = s[2] ^ c_rk[2], s3 = s[3] ^ c_rk[3];
#pragma unroll
    for (int r = 1; r < 10; r++) {
        uint32_t t0 = te0[s0 >> 24] ^ rotr8(te0[(s1 >> 16) & 0xff]) ^ rotr16(te0[(s2 >> 8) & 0xff]) ^ rotr24(te0[s3 & 0xff]) ^ c_rk[4 * r];
        uint32_t t1 = te0[s1 >> 24] ^ rotr8(te0[(s2 >> 16) & 0xff]) ^ rotr16(te0[(s3 >> 8) & 0xff]) ^ rotr24(te0[s0 & 0xff]) ^ c_rk[4 * r + 1];
        uint32_t t2 = te0[s2 >> 24] ^ rotr8(te0[(s3 >> 16) & 0xff]) ^ rotr16(te0[(s0 >> 8) & 0xff]) ^ rotr24(te0[s1 & 0xff]) ^ c_rk[4 * r + 2];
        uint32_t t3 = te0[s3 >> 24] ^ rotr8(te0[(s0 >> 16) & 0xff]) ^ rotr16(te0[(s1 >> 8) & 0xff]) ^ rotr24(te0[s2 & 0xff]) ^ c_rk[4 * r + 3];
        s0 = t0; s1 = t1; s2 = t2; s3 = t3;
    }
    s[0] = (((uint32_t)sb[s0 >> 24] << 24) | ((uint32_t)sb[(s1 >> 16) & 0xff] << 16) | ((uint32_t)sb[(s2 >> 8) & 0xff] << 8) | sb[s3 & 0xff]) ^ c_rk[40];
    s[1] = (((uint32_t)sb[s1 >> 24] << 24) | ((uint32_t)sb[(s2 >> 16) & 0xff] << 16) | ((uint32_t)sb[(s3 >> 8) & 0xff] << 8) | sb[s0 & 0xff]) ^ c_rk[41];
    s[2] = (((uint32_t)sb[s2 >> 24] << 24) | ((uint32_t)sb[(s3 >> 16) & 0xff] << 16) | ((uint32_t)sb[(s0 >> 8) & 0xff] << 8) | sb[s1 & 0xff]) ^ c_rk[42];
    s[3] = (((uint32_t)sb[s3 >> 24] << 24) | ((uint32_t)sb[(s0 >> 16) & 0xff] << 16) | ((uint32_t)sb[(s1 >> 8) & 0xff] << 8) | sb[s2 & 0xff]) ^ c_rk[43];
}

__device__ __forceinline__ void decrypt_block(const uint32_t *td0, const uint8_t *isb, uint32_t s[4]) {
    uint32_t s0 = s[0] ^ c_drk[0], s1 = s[1] ^ c_drk[1], s2 = s[2] ^ c_drk[2], s3 = s[3] ^ c_drk[3];
#pragma unroll
    for (int r = 1; r < 10; r++) {
        uint32_t t0 = td0[s0 >> 24] ^ rotr8(td0[(s3 >> 16) & 0xff]) ^ rotr16(td0[(s2 >> 8) & 0xff]) ^ rotr24(td0[s1 & 0xff]) ^ c_drk[4 * r];
        uint32_t t1 = td0[s1 >> 24] ^ rotr8(td0[(s0 >> 16) & 0xff]) ^ rotr16(td0[(s3 >> 8) & 0xff]) ^ rotr24(td0[s2 & 0xff]) ^ c_drk[4 * r + 1];
        uint32_t t2 = td0[s2 >> 24] ^ rotr8(td0[(s1 >> 16) & 0xff]) ^ rotr16(td0[(s0 >> 8) & 0xff]) ^ rotr24(td0[s3 & 0xff]) ^ c_drk[4 * r + 2];
        uint32_t t3 = td0[s3 >> 24] ^ rotr8(td0[(s2 >> 16) & 0xff]) ^ rotr16(td0[(s1 >> 8) & 0xff]) ^ rotr24(td0[s0 & 0xff]) ^ c_drk[4 * r + 3];
        s0 = t0; s1 = t1; s2 = t2; s3 = t3;
    }
    s[0] = (((uint32_t)isb[s0 >> 24] << 24) | ((uint32_t)isb[(s3 >> 16) & 0xff] << 16) | ((uint32_t)isb[(s2 >> 8) & 0xff] << 8) | isb[s1 & 0xff]) ^ c_drk[40];
    s[1] = (((uint32_t)isb[s1 >> 24] << 24) | ((uint32_t)isb[(s0 >> 16) & 0xff] << 16) | ((uint32_t)isb[(s3 >> 8) & 0xff] << 8) | isb[s2 & 0xff]) ^ c_drk[41];
    s[2] = (((uint32_t)isb[s2 >> 24] << 24) | ((uint32_t)isb[(s1 >> 16) & 0xff] << 16) | ((uint32_t)isb[(s0 >> 8) & 0xff] << 8) | isb[s3 & 0xff]) ^ c_drk[42];
    s[3] = (((uint32_t)isb[s3 >> 24] << 24) | ((uint32_t)isb[(s2 >> 16) & 0xff] << 16) | ((uint32_t)isb[(s1 >> 8) & 0xff] << 8) | isb[s0 & 0xff]) ^ c_drk[43];
}

__device__ __forceinline__ void load_be(const uint4 v, uint32_t s[4]) {
    s[0] = bswap(v.x); s[1] = bswap(v.y); s[2] = bswap(v.z); s[3] = bswap(v.w);
}
__device__ __forceinline__ uint4 store_be(const uint32_t s[4]) {
    return make_uint4(bswap(s[0]), bswap(s[1]), bswap(s[2]), bswap(s[3]));
}

extern "C" __global__ void aes128_ecb_encrypt(const uint4 *in, uint4 *out, size_t nblocks) {
    __shared__ uint32_t te0[256];
    __shared__ uint8_t sb[256];
    build_enc_tables(te0, sb);
    for (size_t i = (size_t)blockIdx.x * blockDim.x + threadIdx.x; i < nblocks; i += (size_t)gridDim.x * blockDim.x) {
        uint32_t s[4];
        load_be(in[i], s);
        encrypt_block(te0, sb, s);
        out[i] = store_be(s);
    }
}

extern "C" __global__ void aes128_ecb_decrypt(const uint4 *in, uint4 *out, size_t nblocks) {
    __shared__ uint32_t td0[256];
    __shared__ uint8_t isb[256];
    build_dec_tables(td0, isb);
    for (size_t i = (size_t)blockIdx.x * blockDim.x + threadIdx.x; i < nblocks; i += (size_t)gridDim.x * blockDim.x) {
        uint32_t s[4];
        load_be(in[i], s);
        decrypt_block(td0, isb, s);
        out[i] = store_be(s);
    }
}

// Counter mode as in NIST SP 800-38A: the counter block of block i is the
// initial counter block (iv0..iv3, big-endian words) plus i, as a 128-bit integer.
extern "C" __global__ void aes128_ctr_xcrypt(const uint4 *in, uint4 *out, size_t nblocks,
                                             uint32_t iv0, uint32_t iv1, uint32_t iv2, uint32_t iv3) {
    __shared__ uint32_t te0[256];
    __shared__ uint8_t sb[256];
    build_enc_tables(te0, sb);
    const uint64_t hi = ((uint64_t)iv0 << 32) | iv1, lo = ((uint64_t)iv2 << 32) | iv3;
    for (size_t i = (size_t)blockIdx.x * blockDim.x + threadIdx.x; i < nblocks; i += (size_t)gridDim.x * blockDim.x) {
        uint64_t l = lo + (uint64_t)i;
        uint64_t h = hi + (l < lo ? 1 : 0);
        uint32_t s[4] = {(uint32_t)(h >> 32), (uint32_t)h, (uint32_t)(l >> 32), (uint32_t)l};
        encrypt_block(te0, sb, s);
        uint4 v = in[i];
        out[i] = make_uint4(v.x ^ bswap(s[0]), v.y ^ bswap(s[1]), v.z ^ bswap(s[2]), v.w ^ bswap(s[3]));
    }
}

